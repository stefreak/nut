/**
 * Apply template data to a workspace
 * This is called after creating a workspace from a template
 * 
 * Tauri: This will be handled by the backend when creating from template
 */
export async function applyTemplateToWorkspace(
  workspaceId: string,
  repositories: Array<{ owner: string; name: string }>,
  links: PackageLink[]
): Promise<void> {
  // Convert template repos to Repository objects with default values
  const repoObjects: Repository[] = repositories.map(repo => ({
    name: repo.name,
    owner: repo.owner,
    branch: 'main',
    status: 'clean' as const,
    url: `https://github.com/${repo.owner}/${repo.name}`,
  }));

  // Convert template repos to RepositoryWithPackages
  // Try to get package data from the registry, fallback to empty
  const packageRepos: RepositoryWithPackages[] = repositories.map(repo => {
    const repoFullName = `${repo.owner}/${repo.name}`;
    const registryData = getRepositoryData(repoFullName);
    
    if (registryData) {
      return registryData;
    }
    
    // Fallback if not in registry
    return {
      name: repo.name,
      owner: repo.owner,
      packages: [],
    };
  });

  // Activate all links from the template (set status to 'linked')
  const activatedLinks = links.map(link => ({
    ...link,
    status: 'linked' as const,
  }));

  const dataToStore = {
    repositories: repoObjects,
    packageLinks: activatedLinks,
    packageRepositories: packageRepos,
  };
  
  workspaceDataStore.set(workspaceId, dataToStore);
  
  // Small delay to ensure data is stored before any reads
  await new Promise(resolve => setTimeout(resolve, 10));
}