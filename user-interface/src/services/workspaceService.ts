/**
 * Get workspace data including repositories, PRs, activities, and packages
 * 
 * Tauri command: invoke('get_workspace_data', { workspaceId })
 */
export async function getWorkspaceData(workspaceId: string): Promise<WorkspaceData> {
  // Simulate async operation
  await new Promise(resolve => setTimeout(resolve, 50));
  
  // Check if we have template data for this workspace
  const templateData = workspaceDataStore.get(workspaceId);
  
  if (templateData) {
    // Get default data for PRs and activities (which templates don't include)
    const defaultData = getDummyWorkspaceData(workspaceId);
    const result = {
      repositories: templateData.repositories || defaultData.repositories,
      packageLinks: templateData.packageLinks || defaultData.packageLinks,
      packageRepositories: templateData.packageRepositories || defaultData.packageRepositories,
      pullRequests: defaultData.pullRequests,
      activities: defaultData.activities,
    };
    return result;
  }
  
  return getDummyWorkspaceData(workspaceId);
}

